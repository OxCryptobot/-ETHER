def test_d1_gems_do_not_import_core_beyond_leaf_contracts():
    sites = set()
    for p in _py_files("gems"):
        for line, mod, _fn in _imports(p):
            top = mod.lstrip(".").split(".")[0]
            if top != "core":
                continue
            if any(mod == ok or mod.startswith(ok + ".") for ok in _D1_LEGAL):
                continue
            sites.add((_rel(p), line, mod))
    new = sites - D1_ALLOWLIST
    assert not new, (
        "D1: NEW gems→core imports (layering inversion). Gems may only import "
        f"{_D1_LEGAL} from core; constructor-inject everything else:\n"
        + "\n".join(f"  {f}:{ln} imports {m}" for f, ln, m in sorted(new))
    )



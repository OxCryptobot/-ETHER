"""Topology guards D1–D5 — AST-walking architecture ratchets (no imports of
the audited code; stdlib ast only).

Each rule collects (file, line, ...) sites and compares them against an
EMBEDDED explicit allowlist generated by scanning ETHER @208993a. A NEW site
fails the test with a clear message; sites disappearing is fine (shrink-only
ratchet — when a grandfathered site is removed, delete it from the list).
"""

from __future__ import annotations

import ast
from pathlib import Path
from typing import Iterator, List, Optional, Set, Tuple

REPO = Path(__file__).resolve().parents[1]

_SKIP_DIRS = {".git", ".venv", "__pycache__", "node_modules", "memory"}


def _py_files(*roots: str) -> Iterator[Path]:
    for root in roots:
        for p in sorted((REPO / root).rglob("*.py")):
            if any(part in _SKIP_DIRS for part in p.parts):
                continue
            yield p


def _imports(path: Path) -> Iterator[Tuple[int, str, Optional[str]]]:
    """Yield (line, module, enclosing_function) for every import in path."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))

    def walk(node: ast.AST, fn: Optional[str]) -> Iterator[Tuple[int, str, Optional[str]]]:
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                yield from walk(child, child.name)
            elif isinstance(child, ast.Import):
                for a in child.names:
                    yield (child.lineno, a.name, fn)
            elif isinstance(child, ast.ImportFrom):
                mod = ("." * child.level) + (child.module or "")
                yield (child.lineno, mod, fn)
            else:
                yield from walk(child, fn)

    yield from walk(tree, None)


def _rel(p: Path) -> str:
    return p.relative_to(REPO).as_posix()



_D4_READ_NAMES = ("open", "read_text", "read_bytes", "glob", "rglob", "_read_json")
_D4_MEM_MARKERS = ('"memory', "'memory", "memory/")


def test_d4_dashboard_reads_via_collector_only():
    sites = set()
    for p in _py_files("dashboard"):
        rel = _rel(p)
        if rel == "dashboard/collector.py":
            continue
        tree = ast.parse(p.read_text(encoding="utf-8"), filename=rel)
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            fn = _call_name(node.func)
            if not (fn.endswith(_D4_READ_NAMES) or fn == "open"):
                continue
            hay = ast.dump(node)
            if any(m in hay for m in _D4_MEM_MARKERS):
                sites.add((rel, node.lineno))
    new = sites - D4_ALLOWLIST
    assert not new, (
        "D4: NEW direct memory/ reads in dashboard/ outside "
        "dashboard/collector.py — dashboard panels read through the collector "
        "API:\n" + "\n".join(f"  {f}:{ln}" for f, ln in sorted(new))
    )



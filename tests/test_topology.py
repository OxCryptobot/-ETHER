def _call_name(func: ast.AST) -> str:
    name = ""
    while isinstance(func, ast.Attribute):
        name = "." + func.attr + name
        func = func.value
    if isinstance(func, ast.Name):
        name = func.id + name
    return name


def _is_write_call(node: ast.Call) -> bool:
    fn = _call_name(node.func)
    if fn.endswith(_WRITE_NAMES):
        return True
    if fn.endswith("open") or fn == "open":
        for a in list(node.args[1:]) + [k.value for k in node.keywords if k.arg == "mode"]:
            if (
                isinstance(a, ast.Constant)
                and isinstance(a.value, str)
                and any(m in a.value for m in ("w", "a", "+"))
            ):
                return True
    if fn.endswith(".replace"):  # atomic rename target
        return True
    return False


def _targets_state(node: ast.Call) -> bool:
    dump = ast.dump(node)
    return any(h in dump for h in _STATE_HINTS)


def test_d3_spine_kernel_stays_clean():
    for rel in ("core/spine/state_io.py",):
        for line, mod, _fn in _imports(REPO / rel):
            assert not (mod == "core.pipeline" or mod.startswith("core.pipeline.")), (
                f"D3: {rel}:{line} imports {mod} — the Spine kernel must not "
                "depend on the pipeline god object"
            )
            assert not _is_gems(mod), (
                f"D3: {rel}:{line} imports {mod} — the Spine kernel must not " "depend on gems"
            )


def test_d3_no_new_state_writers():
    sites = set()
    for p in _py_files("cli", "core", "dashboard", "gems", "scripts", "tools"):
        rel = _rel(p)
        if rel in _D3_WRITER_MODULES:
            continue
        tree = ast.parse(p.read_text(encoding="utf-8"), filename=rel)
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and _is_write_call(node) and _targets_state(node):
                sites.add((rel, node.lineno))
    new = sites - D3_ALLOWLIST
    assert not new, (
        "D3: NEW memory/ state writers outside the single-writer allowlist. "
        "Route the write through core/spine/state_io.py (rmw / write_json / "
        "append_jsonl):\n" + "\n".join(f"  {f}:{ln}" for f, ln in sorted(new))
    )



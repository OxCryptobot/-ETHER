def test_d2_hard_zero_new_layers():
    """core/loop/**, core/spine/**, core/vectors.py: ZERO gems imports, with the
    single exception of LoopRunner._default_run_tool (spec §3, D2 note)."""
    offenders: List[str] = []
    for p in list(_py_files("core/loop", "core/spine")) + [REPO / "core" / "vectors.py"]:
        rel = _rel(p)
        for line, mod, fn in _imports(p):
            if not _is_gems(mod):
                continue
            if (rel, mod, fn) == D2_SANCTIONED_GEM_BRIDGE:
                continue
            offenders.append(f"  {rel}:{line} imports {mod}")
    assert not offenders, (
        "D2 HARD RULE: core/loop, core/spine and core/vectors.py must have "
        "ZERO gems imports (gem access is constructor-injected; the only "
        "sanctioned bridge is LoopRunner._default_run_tool):\n" + "\n".join(offenders)
    )


